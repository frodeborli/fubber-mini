#!/usr/bin/env php
<?php

/**
 * mini aspects — sync aspects/ bundles with Composer and bootstrap files.
 *
 * Usage:
 *   mini aspects          # default: sync state
 *   mini aspects list     # read-only listing
 *
 * For each subdirectory in <host>/aspects/, this command:
 *   1. Ensures aspects/<name>/composer.json exists (creates if missing).
 *   2. Ensures aspects/<name>/_bootstrap.php exists, with a managed block of
 *      addPath() calls reflecting whichever resource directories the aspect
 *      actually has (_routes, _views, _config, _translations, _static,
 *      _migrations). Any custom code after the END marker is preserved.
 *   3. Patches the host composer.json so it knows about aspects/* via a path
 *      repository and a require entry per aspect.
 *   4. Runs `composer update` scoped to any newly-added aspect packages.
 *
 * Existing files are never overwritten beyond the managed block.
 */

/**
 * Marker that identifies an auto-generated _bootstrap.php so the tool knows
 * it's safe to overwrite. Hand-written _bootstrap.php files (no marker) are
 * skipped with a warning.
 */
const AUTOGEN_MARKER = 'AUTO-GENERATED by `mini aspects`';

$hostRoot = findHostRoot(getcwd());
if ($hostRoot === null) {
    fwrite(STDERR, "Could not find host composer.json by walking up from " . getcwd() . "\n");
    exit(1);
}

$subcommand = $argv[1] ?? 'sync';
if ($subcommand === '--help' || $subcommand === '-h' || $subcommand === 'help') {
    echo <<<'TXT'
Mini Aspect Bundles

Keeps aspects/<name>/ bundles wired into the host project: each aspect is a
real Composer path package with an auto-generated _bootstrap.php that
registers its resource directories (_routes, _views, _config, _translations,
_static, _migrations).

Usage:
  mini aspects [command]

Commands:
  sync          Sync aspects/* with Composer + bootstrap files (default)
  list          Show discovered aspects, package names, and registered paths

Options:
  -h, --help    Show this help

Examples:
  mini aspects            Scaffold/update all aspects and patch composer.json
  mini aspects list       Read-only overview of discovered aspects

Custom bootstrap code belongs in aspects/<name>/bootstrap.php (no underscore);
_bootstrap.php is regenerated on every sync.

TXT;
    exit(0);
}

$aspectsDir = $hostRoot . '/aspects';
if (!is_dir($aspectsDir)) {
    echo "No aspects/ directory in $hostRoot — nothing to do.\n";
    exit(0);
}

$hostComposer = readJson($hostRoot . '/composer.json');
$hostVendor = explode('/', $hostComposer['name'] ?? 'app/app')[0];

$discovered = [];
foreach (sort_glob($aspectsDir . '/*') as $path) {
    if (!is_dir($path)) continue;
    $name = basename($path);
    if ($name[0] === '.' || $name[0] === '_') continue; // skip hidden / scratch dirs
    $discovered[$name] = $path;
}

if (!$discovered) {
    echo "No aspects under $aspectsDir.\n";
    exit(0);
}

if ($subcommand === 'list') {
    listAspects($discovered, $hostVendor);
    exit(0);
}

if ($subcommand !== 'sync') {
    fwrite(STDERR, "Unknown subcommand: $subcommand\n");
    fwrite(STDERR, "Try: mini aspects [list]\n");
    exit(1);
}

// ---- sync flow ----

$summary = [
    'created_composer' => [],
    'created_bootstrap' => [],
    'updated_bootstrap' => [],
    'skipped_bootstrap' => [],
];

foreach ($discovered as $name => $path) {
    $packageName = "$hostVendor/aspect-$name";
    $composerPath = "$path/composer.json";
    $bootstrapPath = "$path/_bootstrap.php";

    if (!file_exists($composerPath)) {
        writeJson($composerPath, scaffoldAspectComposer($packageName, $name, $path));
        $summary['created_composer'][] = $name;
    }

    $status = syncBootstrapFile($bootstrapPath, $path);
    if ($status === 'created') {
        $summary['created_bootstrap'][] = $name;
    } elseif ($status === 'updated') {
        $summary['updated_bootstrap'][] = $name;
    } elseif ($status === 'skipped-handwritten') {
        $summary['skipped_bootstrap'][] = $name;
    }
}

// Patch host composer.json
$hostChanged = false;

$hostComposer['repositories'] ??= [];
$hasAspectsRepo = false;
foreach ($hostComposer['repositories'] as $repo) {
    if (($repo['type'] ?? null) === 'path' && ($repo['url'] ?? null) === 'aspects/*') {
        $hasAspectsRepo = true;
        break;
    }
}
if (!$hasAspectsRepo) {
    $hostComposer['repositories'][] = [
        'type' => 'path',
        'url' => 'aspects/*',
        'options' => ['symlink' => true],
    ];
    $hostChanged = true;
}

$hostComposer['require'] ??= [];
$newlyRequired = [];
foreach ($discovered as $name => $_path) {
    $pkg = "$hostVendor/aspect-$name";
    if (!array_key_exists($pkg, $hostComposer['require'])) {
        $hostComposer['require'][$pkg] = '*';
        $newlyRequired[] = $pkg;
        $hostChanged = true;
    }
}

// Warn on orphaned aspect requires (host requires a frode/aspect-X but aspects/X/ doesn't exist)
$orphans = [];
foreach ($hostComposer['require'] as $pkg => $_) {
    if (!str_starts_with($pkg, "$hostVendor/aspect-")) continue;
    $name = substr($pkg, strlen("$hostVendor/aspect-"));
    if (!isset($discovered[$name])) {
        $orphans[] = $pkg;
    }
}

if ($hostChanged) {
    writeJson($hostRoot . '/composer.json', $hostComposer);
}

// Run composer update scoped to newly-required aspects (or full update if repos changed)
$didComposer = false;
if ($newlyRequired) {
    echo "Composer update: " . implode(' ', $newlyRequired) . "\n";
    passthru('composer -d ' . escapeshellarg($hostRoot) . ' update ' . implode(' ', array_map('escapeshellarg', $newlyRequired)) . ' 2>&1', $rc);
    if ($rc !== 0) {
        fwrite(STDERR, "composer update failed (exit $rc)\n");
        exit($rc);
    }
    $didComposer = true;
} elseif ($hostChanged) {
    // repository entry added but no new requires (rare) — dump-autoload is enough
    echo "Composer dump-autoload\n";
    passthru('composer -d ' . escapeshellarg($hostRoot) . ' dump-autoload 2>&1', $rc);
    if ($rc !== 0) exit($rc);
    $didComposer = true;
} elseif ($summary['updated_bootstrap']) {
    // Aspect's _bootstrap.php changed (autoload.files entry already pointed at it,
    // so no Composer regen is required). Still report so it's visible.
    $didComposer = false;
}

// ---- summary ----
$any = false;
$labels = [
    'created_composer' => 'Created composer.json',
    'created_bootstrap' => 'Created _bootstrap.php',
    'updated_bootstrap' => 'Updated _bootstrap.php',
];
foreach ($labels as $key => $label) {
    foreach ($summary[$key] as $name) {
        echo "  $label: aspects/$name/\n";
        $any = true;
    }
}
foreach ($summary['skipped_bootstrap'] as $name) {
    echo "  Skipped (hand-written _bootstrap.php): aspects/$name/\n";
    echo "    To let `mini aspects` manage this file, delete _bootstrap.php and re-run.\n";
    echo "    Move custom code into `bootstrap.php` (no underscore) — it's auto-included.\n";
    $any = true;
}
if ($hasAspectsRepo === false) {
    echo "  Added path repository to host composer.json (aspects/*)\n";
    $any = true;
}
if ($newlyRequired) {
    foreach ($newlyRequired as $pkg) {
        echo "  Required: $pkg\n";
    }
    $any = true;
}
if (!$any && !$didComposer) {
    echo "Up to date — " . count($discovered) . " aspect(s) discovered, nothing to change.\n";
}
if ($orphans) {
    echo "\nWarning: host composer.json requires packages whose aspect directory no longer exists:\n";
    foreach ($orphans as $pkg) echo "  $pkg\n";
    echo "Remove these manually with: composer remove " . implode(' ', $orphans) . "\n";
}

exit(0);

// ============================================================================

function findHostRoot(string $cwd): ?string
{
    $dir = $cwd;
    while ($dir !== '/' && $dir !== '') {
        if (file_exists("$dir/composer.json") && !str_contains($dir, '/vendor/')) {
            return $dir;
        }
        $parent = dirname($dir);
        if ($parent === $dir) break;
        $dir = $parent;
    }
    return null;
}

function readJson(string $path): array
{
    $raw = file_get_contents($path);
    if ($raw === false) {
        fwrite(STDERR, "Could not read $path\n");
        exit(1);
    }
    $data = json_decode($raw, true);
    if (!is_array($data)) {
        fwrite(STDERR, "Could not parse $path as JSON\n");
        exit(1);
    }
    return $data;
}

function writeJson(string $path, array $data): void
{
    $encoded = json_encode($data, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES) . "\n";
    if (file_put_contents($path, $encoded) === false) {
        fwrite(STDERR, "Could not write $path\n");
        exit(1);
    }
}

function sort_glob(string $pattern): array
{
    $list = glob($pattern) ?: [];
    sort($list);
    return $list;
}

function scaffoldAspectComposer(string $packageName, string $aspectName, string $aspectPath): array
{
    $composer = [
        'name' => $packageName,
        'description' => "Mini aspect: $aspectName",
        'type' => 'mini-aspect',
        'license' => 'proprietary',
        'require' => [
            'fubber/mini' => '*',
        ],
        'autoload' => [
            'files' => ['_bootstrap.php'],
        ],
    ];

    if (is_dir("$aspectPath/src")) {
        // Convention: namespace = inferred from package vendor + camel-cased aspect name
        [$vendor] = explode('/', $packageName);
        $ns = ucfirst($vendor) . '\\Aspect\\' . toCamelCase($aspectName) . '\\';
        $composer['autoload']['psr-4'] = [$ns => 'src/'];
    }

    if (is_dir("$aspectPath/bin")) {
        $bins = glob("$aspectPath/bin/*") ?: [];
        $bins = array_filter($bins, 'is_file');
        if ($bins) {
            sort($bins);
            $composer['bin'] = array_map(fn($p) => 'bin/' . basename($p), $bins);
        }
    }

    return $composer;
}

function toCamelCase(string $name): string
{
    return str_replace(' ', '', ucwords(str_replace(['-', '_'], ' ', $name)));
}

/**
 * Sync an aspect's _bootstrap.php. The file is fully regenerated on every run.
 * Custom user bootstrap belongs in a separate `bootstrap.php` (no underscore),
 * which the generated _bootstrap.php includes if present.
 *
 * Returns one of: 'created', 'updated', 'unchanged', 'skipped-handwritten'.
 */
function syncBootstrapFile(string $path, string $aspectDir): string
{
    $generated = buildBootstrapFile($aspectDir);

    if (!file_exists($path)) {
        file_put_contents($path, $generated);
        return 'created';
    }

    $current = file_get_contents($path);
    if (!str_contains($current, AUTOGEN_MARKER)) {
        // Hand-written file — leave it alone so we don't clobber the user's work.
        return 'skipped-handwritten';
    }

    if ($current === $generated) {
        return 'unchanged';
    }

    file_put_contents($path, $generated);
    return 'updated';
}

function buildBootstrapFile(string $aspectDir): string
{
    $resources = detectResourceDirs($aspectDir);
    $marker = AUTOGEN_MARKER;

    $lines = ["<?php\n", "/**"];
    $lines[] = " * $marker — DO NOT EDIT.";
    $lines[] = " *";
    $lines[] = " * This file is regenerated on every `mini aspects` run. To add custom";
    $lines[] = " * bootstrap code for this aspect (register services, container bindings,";
    $lines[] = " * middleware, etc.), create a sibling `bootstrap.php` (no underscore).";
    $lines[] = " * It will be required automatically after the resource paths are added.";
    $lines[] = " */";
    $lines[] = "";

    if ($resources) {
        foreach ($resources as $registry => $dir) {
            $lines[] = "\\mini\\Mini::\$mini->paths->{$registry}->addPath(__DIR__ . '/{$dir}');";
        }
    } else {
        $lines[] = "// (No resource directories detected in this aspect.)";
    }

    $lines[] = "";
    $lines[] = "if (is_file(__DIR__ . '/bootstrap.php')) {";
    $lines[] = "    require __DIR__ . '/bootstrap.php';";
    $lines[] = "}";

    return implode("\n", $lines) . "\n";
}

function detectResourceDirs(string $aspectDir): array
{
    $candidates = [
        'routes' => '_routes',
        'views' => '_views',
        'config' => '_config',
        'translations' => '_translations',
        'static' => '_static',
        'migrations' => '_migrations',
    ];
    $found = [];
    foreach ($candidates as $registry => $dir) {
        if (is_dir("$aspectDir/$dir")) {
            $found[$registry] = $dir;
        }
    }
    return $found;
}

function buildManagedBlock(array $resources): string
{
    $lines = ["// === BEGIN: managed by `mini aspects` ==="];
    if (!$resources) {
        $lines[] = "// (no resource directories detected)";
    }
    foreach ($resources as $registry => $dir) {
        $lines[] = "\\mini\\Mini::\$mini->paths->{$registry}->addPath(__DIR__ . '/{$dir}');";
    }
    $lines[] = "// === END: managed by `mini aspects` ===";
    return implode("\n", $lines) . "\n";
}

function listAspects(array $discovered, string $hostVendor): void
{
    echo "Discovered aspects:\n";
    foreach ($discovered as $name => $path) {
        $pkg = "$hostVendor/aspect-$name";
        $resources = detectResourceDirs($path);
        $hasAutoBootstrap = file_exists("$path/_bootstrap.php");
        $hasUserBootstrap = file_exists("$path/bootstrap.php");
        echo "  $name\n";
        echo "    package:   $pkg\n";
        echo "    path:      $path\n";
        echo "    resources: " . ($resources ? implode(', ', array_values($resources)) : '(none)') . "\n";
        echo "    composer:  " . (file_exists("$path/composer.json") ? 'yes' : 'MISSING') . "\n";
        echo "    _bootstrap.php: " . ($hasAutoBootstrap ? 'yes (auto-generated)' : 'MISSING') . "\n";
        echo "    bootstrap.php:  " . ($hasUserBootstrap ? 'yes (user)' : '(none)') . "\n";
    }
}
